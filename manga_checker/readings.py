_PUNCT = re.compile(r"[\s・/／\-−_.,.'\"「」『』()（）\[\]【】]+")


def to_hiragana(text: str) -> str:
    text = unicodedata.normalize("NFKC", text or "")
    out: list[str] = []
    for ch in text:
        code = ord(ch)
        if 0x30A1 <= code <= 0x30F6:
            out.append(chr(code - 0x60))
        else:
            out.append(ch)
    return "".join(out).lower()


def kana_to_romaji(text: str) -> str:
    hira = to_hiragana(text)
    result: list[str] = []
    i = 0
    while i < len(hira):
        if hira[i] == "っ" and i + 1 < len(hira):
            nxt = kana_to_romaji(hira[i + 1 :])
            if nxt:
                result.append(nxt[0] if nxt[0] != "c" else "t")
            i += 1
            continue
        two = hira[i : i + 2]
        if two in _DIGRAPHS:
            result.append(_DIGRAPHS[two])
            i += 2
            continue
        ch = hira[i]
        if ch in _MONO:
            result.append(_MONO[ch])
        elif ch.isascii() and ch.isalnum():
            result.append(ch.lower())
        i += 1
    return "".join(result)


def readings_for(ch: str) -> tuple[str, ...]:
    if ch in KANJI_READINGS:
        return KANJI_READINGS[ch]
    if len(ch) > 1 and ch in KANJI_READINGS:
        return KANJI_READINGS[ch]
    return ()


def expand_title_readings(title: str) -> list[str]:
    """漢字ごとに音訓を展開し、短いタイトルは組み合わせも作る。"""
    if not title:
        return []
    tokens: list[list[str]] = []
    for ch in title:
        mapped = readings_for(ch)
        if mapped:
            tokens.append(list(dict.fromkeys(mapped)))
        else:
            tokens.append([to_hiragana(ch)])
    found: list[str] = []
    for group in tokens:
        found.extend(group)
    for compound, mapped in KANJI_READINGS.items():
        if len(compound) > 1 and compound in title:
            found.extend(mapped)
    combo_count = 1
    for group in tokens:
        combo_count *= max(1, len(group))
        if combo_count > 64:
            combo_count = 65
            break
    if combo_count <= 64:
        for combo in itertools.product(*tokens):
            found.append("".join(combo))
    return list(dict.fromkeys(item for item in found if item.strip()))


def search_index_text(
    title: str,
    author: str = "",
    publisher: str = "",
    title_kana: str = "",
    author_kana: str = "",
    series: str = "",
) -> str:
    parts = [title, author, publisher, title_kana, author_kana, series]
    hira_kana = to_hiragana(title_kana)
    if hira_kana:
        parts.append(hira_kana)
        parts.append(kana_to_romaji(hira_kana))
    if author_kana:
        parts.append(to_hiragana(author_kana))
        parts.append(kana_to_romaji(author_kana))
    for reading in expand_title_readings(title):
        parts.append(reading)
        parts.append(kana_to_romaji(reading))
    blob = " ".join(part for part in parts if part)
    return _PUNCT.sub(" ", blob).strip()
